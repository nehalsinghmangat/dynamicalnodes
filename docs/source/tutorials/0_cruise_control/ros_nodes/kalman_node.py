# ──────────────────────────────────────────────────────────────────────
# Imports
# ──────────────────────────────────────────────────────────────────────

from collections import deque
import numpy as np

import rclpy
from rclpy.node import Node
from rclpy.executors import ExternalShutdownException, SingleThreadedExecutor
from rclpy.callback_groups import ReentrantCallbackGroup
from rclpy.qos import QoSProfile, QoSHistoryPolicy, QoSReliabilityPolicy

from std_msgs.msg import Float64

from dynamicalnodes import DynamicalSystem
from dynamicalnodes.ros2py_py2ros import ros2py_float64, py2ros_float64


# ──────────────────────────────────────────────────────────────────────
# Functions — inlined from source
# ──────────────────────────────────────────────────────────────────────

def fkf(
    ok: tuple[np.ndarray, np.ndarray],
    Fk: np.ndarray,
    Bk: np.ndarray,
    Hk: np.ndarray,
    Qk: np.ndarray,
    Rk: np.ndarray,
    uk: np.ndarray | None = None,
    yk: np.ndarray | None = None,
) -> tuple[np.ndarray, np.ndarray]:
    """Discrete Kalman filter in prior form: ok = (xhat_{k|k-1}, P_{k|k-1}).

    Update with yk (the measurement of x_k), then predict with uk to give
    ok_next = (xhat_{k+1|k}, P_{k+1|k}). Both uk and yk are optional: update
    runs only when yk is fresh, predict only when uk is fresh. With
    sync_mode="any" each subscription triggers the node independently, so a
    step may see just one of them.
    """
    xhat, P = ok
    # Update
    if yk is not None:
        S = Hk @ P @ Hk.T + Rk
        K = P @ Hk.T @ np.linalg.inv(S)
        xhat = xhat + K @ (np.atleast_1d(yk) - Hk @ xhat)
        P = (np.eye(len(xhat)) - K @ Hk) @ P
    # Predict
    if uk is not None:
        xhat = Fk @ xhat + Bk @ np.atleast_1d(uk)
        P = Fk @ P @ Fk.T + Qk
    return (xhat, P)


def hkf(ok: tuple[np.ndarray, np.ndarray]) -> np.ndarray:
    xhat, P = ok
    return xhat


# ──────────────────────────────────────────────────────────────────────
# QoS — tune history / depth / reliability to match your transport
# ──────────────────────────────────────────────────────────────────────

QOS = QoSProfile(
    history=QoSHistoryPolicy.KEEP_LAST,
    depth=10,
    reliability=QoSReliabilityPolicy.RELIABLE,
)


class KalmanNode(Node):

    """
    Subscribes to:
        /uk  (Float64)  →  uk: ndarray | None  [ros2py_float64, buffer=1, stale_after=0.15s]
        /yk  (Float64)  →  yk: ndarray | None  [ros2py_float64, buffer=1, stale_after=0.15s]
    Publishes to:
        /xhatk  (Float64)  [py2ros_float64]

    step trigger: event-driven (fires on each subscription callback)
    sync_mode='any': step when any subscription receives a fresh value.
    """

    def __init__(self) -> None:
        super().__init__("kalman")
        self._cb_group = ReentrantCallbackGroup()

        self._system = DynamicalSystem(f=fkf, h=hkf)
        self._state = (np.array([0.0]), np.array([[1.0]]))  # initial state
        self._t0 = self.get_clock().now()  # wall-clock reference for 'tk'

        self._static_params: dict = {'Fk': np.array([[0.9966666666666667]]), 'Bk': np.array([[6.666666666666667e-05]]), 'Hk': np.array([[1.0]]), 'Qk': np.array([[0.010000000000000002]]), 'Rk': np.array([[2.0]])}  # static params

        # ── Subscription buffers ───────────────────────────────────────────────
        self._uk_buf: deque = deque(maxlen=1)
        self._uk_seen: bool = False  # any message ever received
        self._yk_buf: deque = deque(maxlen=1)
        self._yk_seen: bool = False  # any message ever received

        # ── Subscriptions ────────────────────────────────────────────────────
        self._uk_sub = self.create_subscription(
            Float64, '/uk',
            self._uk_cb, QOS,
            callback_group=self._cb_group,
        )
        self._yk_sub = self.create_subscription(
            Float64, '/yk',
            self._yk_cb, QOS,
            callback_group=self._cb_group,
        )

        # ── Publishers ────────────────────────────────────────────────────────
        self._pub_xhatk = self.create_publisher(
            Float64, '/xhatk', QOS,
        )

        self.get_logger().info("kalman started")

    # ────────────────────────────────────────────────────────────────────
    # Subscription callbacks
    # ────────────────────────────────────────────────────────────────────
    # Each callback converts the incoming message to NumPy, stores it with an
    # arrival timestamp, then attempts a control step. The (time, value) tuple
    # enables the staleness check in _fresh(). _run_step() proceeds only when
    # sync_mode conditions are satisfied, and pops each value it consumes —
    # so a stored value can trigger at most one step before it must be
    # refreshed by new data.

    def _uk_cb(self, msg: Float64) -> None:
        arr = np.asarray(ros2py_float64(msg), dtype=float)  # ROS msg → NumPy
        ts = self.get_clock().now().nanoseconds * 1e-9
        self._uk_buf.append((ts, arr))
        self._uk_seen = True
        self._run_step()

    def _yk_cb(self, msg: Float64) -> None:
        arr = np.asarray(ros2py_float64(msg), dtype=float)  # ROS msg → NumPy
        ts = self.get_clock().now().nanoseconds * 1e-9
        self._yk_buf.append((ts, arr))
        self._yk_seen = True
        self._run_step()

    @staticmethod
    def _fresh(buf: deque, stale_after, now_ts: float):
        """Newest buffered value if its timestamp is within stale_after seconds of now_ts, else None."""
        if not buf:
            return None
        ts, val = buf[-1]
        if stale_after is not None and (now_ts - ts) > stale_after:
            return None
        return val

    # ────────────────────────────────────────────────────────────────────
    # Control step
    # ────────────────────────────────────────────────────────────────────
    # Builds kwargs from static params, dynamic params, fresh subscription
    # values, and current state, then calls DynamicalSystem.step() and
    # publishes. Skipped entirely when sync_mode conditions are not met.

    def _run_step(self) -> None:
        _now = self.get_clock().now()
        now_ts: float = _now.nanoseconds * 1e-9  # ROS clock, seconds since epoch
        tk: float = (_now - self._t0).nanoseconds * 1e-9  # seconds since node started

        # Gather fresh inputs
        uk = self._fresh(self._uk_buf, 0.15, now_ts)
        yk = self._fresh(self._yk_buf, 0.15, now_ts)

        # sync_mode='any'
        if uk is None and yk is None:
            return  # all inputs are stale — skip this tick

        # Consume: pop each fresh value now that we're committing to a
        # step, so it cannot re-trigger another step until genuinely new
        # data arrives (prevents event-driven feedback loops from
        # cascading at an unbounded rate).
        if uk is not None and self._uk_buf:
            self._uk_buf.pop()
        if yk is not None and self._yk_buf:
            self._yk_buf.pop()

        kwargs: dict = {"tk": tk, **self._static_params}
        if uk is not None:
            kwargs["uk"] = uk
        if yk is not None:
            kwargs["yk"] = yk
        if self._state is not None:
            kwargs["ok"] = self._state

        x_next, yk = self._system.step(**kwargs)
        if self._system.f is not None:
            self._state = x_next  # stateful: advance to next state

        _arr = np.asarray(yk, dtype=float).ravel()
        msg = py2ros_float64(_arr)
        if hasattr(msg, 'header'):
            msg.header.stamp = self.get_clock().now().to_msg()
        self._pub_xhatk.publish(msg)


# ──────────────────────────────────────────────────────────────────────
# Entry point
# ──────────────────────────────────────────────────────────────────────

def main() -> None:
    rclpy.init()
    node = KalmanNode()
    executor = SingleThreadedExecutor()
    executor.add_node(node)
    try:
        executor.spin()
    except (KeyboardInterrupt, ExternalShutdownException):
        pass
    finally:
        node.destroy_node()
        if rclpy.ok():
            rclpy.shutdown()


if __name__ == "__main__":
    main()
